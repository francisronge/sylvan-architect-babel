import { inlineWorkerPlugin } from './inlineWorkerPlugin.mjs';
import { build } from 'esbuild';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { copyFile, readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { createHash } from 'node:crypto';

// Both published Orchard pages load identical artifacts. Build from the same
// TreeVisualizer and styles used by the app; cards provide data and chrome only.
await build({
  plugins: [inlineWorkerPlugin()],
  absWorkingDir: fileURLToPath(new URL('..', import.meta.url)),
  entryPoints: ['docs/design/visual-relations-current-lab.tsx'],
  outfile: 'docs/design/visual-relations-current-lab.production-only-audit.r96.bundle.js',
  bundle: true, format: 'iife', jsx: 'automatic', minify: true,
  define: { 'process.env.NODE_ENV': '"production"' }
});
await copyFile(
  new URL('../docs/design/visual-relations-current-lab.production-only-audit.r96.bundle.js', import.meta.url),
  new URL('../docs/research/relation-orchard/relation-orchard.bundle.js', import.meta.url)
);
// The published research site cannot reach components/, so it keeps an exact
// copy of the app's drawing stylesheet; tests/relationVisualStyles.test.mjs checks it.
await copyFile(
  new URL('../components/renderer/relation-visuals.css', import.meta.url),
  new URL('../docs/research/relation-orchard/relation-visuals.css', import.meta.url)
);

// The published pages cannot reach node_modules either, so they load the font
// faces styles.css imports, every weight and unicode subset, from copies here.
// Without them a card paints plaques in a synthesized bold and some glyphs in a
// system font, which the app and the offline audits never measure;
// tests/orchardAppParity.test.mjs checks the copy.
const require = createRequire(import.meta.url);
const appStyles = await readFile(new URL('../styles.css', import.meta.url), 'utf8');
const fontFaces = [];
for (const [, entry] of appStyles.matchAll(/@import '(@fontsource\/[^']+\.css)';/g)) {
  const entryPath = require.resolve(entry);
  const css = await readFile(entryPath, 'utf8');
  for (const [face] of css.matchAll(/@font-face\s*\{[^}]*\}/g)) {
    const file = /url\(\.\/files\/([^)]+\.woff2)\)/.exec(face)?.[1];
    if (!file) throw new Error(`${entry}: a font face without a woff2 file`);
    await copyFile(new URL(`files/${file}`, pathToFileURL(entryPath)),
      new URL(`../docs/research/relation-orchard/assets/fonts/${file}`, import.meta.url));
    fontFaces.push(face.replace(/src:[^;]*;/, `src: url(./assets/fonts/${file}) format('woff2');`));
  }
}
if (!fontFaces.length) throw new Error('styles.css imports no @fontsource faces');
await writeFile(new URL('../docs/research/relation-orchard/fonts.css', import.meta.url),
  `/* Generated by npm run orchard:build from the @fontsource faces styles.css imports. */\n${fontFaces.join('\n')}\n`);

// A new published drawing must not reuse an older cached bundle or source layout.
for (const page of [
  '../docs/design/babel-visual-relations-research.production-only-audit.html',
  '../docs/research/relation-orchard/orchard.html'
]) {
  const location = new URL(page, import.meta.url);
  const html = await readFile(location, 'utf8');
  let updated = html;
  for (const match of html.matchAll(/(?:src|href)="([^"?]+(?:\.bundle\.js|source-citations\.css|fonts\.css))(?:\?[^\"]*)?"/g)) {
    const bytes = await readFile(new URL(match[1], location));
    const version = createHash('sha256').update(bytes).digest('hex').slice(0, 12);
    updated = updated.replace(match[0], match[0].replace(/=".*"$/, `="${match[1]}?v=${version}"`));
  }
  await writeFile(location, updated);
}
