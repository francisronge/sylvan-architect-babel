// A card's Replay chrome (header, controls, canvas) is styled by the app's
// Tailwind utilities and styles.css, which the published Orchard pages cannot
// load whole: they would restyle the page around the cards. This builds the
// same rules with the app's PostCSS plugins and confines them to the card
// mount. Each selector is prefixed with :where(.babel-render-mount), which adds
// no specificity, so inside a card the rules win and lose exactly as in the
// app. Document selectors (html, body, :root) become the mount itself, keeping
// only what the app's chrome inherits from them.
//
// npm run orchard:build writes the result; tests/orchardAppParity.test.mjs
// rebuilds it and compares, so a chrome change in the app fails until the
// Orchard is rebuilt.
import { readFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import postcss from 'postcss';
import tailwindcss from 'tailwindcss';
import autoprefixer from 'autoprefixer';

export const REPLAY_CHROME_PATH = 'docs/research/relation-orchard/replay-chrome.css';

const MOUNT = ':where(.babel-render-mount)';
const DOCUMENT_SELECTORS = new Set(['html', ':host', 'body', ':root']);
const INHERITED = /^(--|font-family$|color$|line-height$|font-feature-settings$|font-variation-settings$|-webkit-text-size-adjust$|-moz-tab-size$|tab-size$|-webkit-tap-highlight-color$)/;

export async function buildReplayChromeCss() {
  const root = new URL('..', import.meta.url);
  const stylesPath = fileURLToPath(new URL('styles.css', root));
  const appConfig = createRequire(import.meta.url)('../tailwind.config.cjs');
  // Font faces reach the pages through fonts.css and the relation styles
  // through relation-visuals.css, so the imports are left out here.
  const source = (await readFile(stylesPath, 'utf8')).replace(/^@import [^;]+;\n/gm, '');
  const { css } = await postcss([
    tailwindcss({ ...appConfig, content: appConfig.content.map(file => fileURLToPath(new URL(file, root))) }),
    autoprefixer()
  ]).process(source, { from: stylesPath });
  const sheet = postcss.parse(css);
  sheet.walkRules((rule) => {
    if (rule.parent?.type === 'atrule' && /keyframes$/.test(rule.parent.name)) return;
    const scoped = rule.selectors.filter(selector => !DOCUMENT_SELECTORS.has(selector)).map(selector => `${MOUNT} ${selector}`);
    if (rule.selectors.some(selector => DOCUMENT_SELECTORS.has(selector))) {
      const inherited = rule.clone({ selector: MOUNT });
      inherited.each(node => { if (node.type === 'decl' && !INHERITED.test(node.prop)) node.remove(); });
      if (inherited.nodes.length) rule.before(inherited);
    }
    if (scoped.length) rule.selectors = scoped;
    else rule.remove();
  });
  return `/* Generated by npm run orchard:build from the app's styles.css and Tailwind utilities, confined to a card mount. */\n${sheet.toString()}\n`;
}
