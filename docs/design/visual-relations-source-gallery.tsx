const sourceAcronyms = new Set([
  'atb', 'cp', 'dp', 'lf', 'mdpi', 'mit', 'np', 'npi', 'pf', 'pic', 'pp', 'qr', 'tp', 'umass', 'vp', 'vpe'
]);

function sourceTitle(path: string): string {
  const fileName = path.split('/').at(-1) ?? path;
  return fileName
    .replace(/\.(?:png|jpe?g|webp|gif)$/i, '')
    .replace(/page(\d+)/gi, 'page $1')
    .split('-')
    .map((word) => sourceAcronyms.has(word.toLowerCase())
      ? word.toUpperCase()
      : `${word.charAt(0).toUpperCase()}${word.slice(1)}`)
    .join(' ');
}
